"use client";
import { useState, useTransition } from "react";
import { useRouter } from "next/navigation";
import { ShieldCheck, ShieldOff, Copy } from "lucide-react";
import { beginTwoFactor, confirmTwoFactor, disableTwoFactor, type Scope } from "@/lib/twofa-actions";

const tx = {
  it: {
    on: "Autenticazione a due fattori attiva", off: "Autenticazione a due fattori non attiva",
    lead: "Al login ti verrà chiesto anche un codice a 6 cifre generato da un'app (Google Authenticator, Aegis, Authy, 1Password…).",
    enable: "Attiva il 2FA", step1: "1. Inquadra il codice QR con la tua app di autenticazione", manual: "Oppure inserisci questa chiave a mano:",
    step2: "2. Scrivi il codice a 6 cifre mostrato dall'app", code: "Codice", confirm: "Conferma e attiva", cancel: "Annulla",
    saved: "2FA attivato. Conserva questi codici di recupero: ognuno vale una volta sola e servono se perdi il telefono. Non verranno più mostrati.",
    done: "Fatto, li ho salvati", copy: "Copia", disableLead: "Per disattivarlo scrivi un codice dell'app (o un codice di recupero).", disable: "Disattiva il 2FA",
    bad: "Codice non corretto.", locked: "Troppi tentativi: riprova tra 15 minuti.", auth: "Sessione scaduta, accedi di nuovo.", generic: "Qualcosa non ha funzionato.",
  },
  en: {
    on: "Two-factor authentication is on", off: "Two-factor authentication is off",
    lead: "At sign-in you will also be asked for a 6-digit code generated by an app (Google Authenticator, Aegis, Authy, 1Password…).",
    enable: "Turn on 2FA", step1: "1. Scan the QR code with your authenticator app", manual: "Or type this key by hand:",
    step2: "2. Enter the 6-digit code shown by the app", code: "Code", confirm: "Confirm and turn on", cancel: "Cancel",
    saved: "2FA is on. Keep these recovery codes: each works once and you need them if you lose your phone. They will not be shown again.",
    done: "Done, I saved them", copy: "Copy", disableLead: "To turn it off, enter a code from the app (or a recovery code).", disable: "Turn off 2FA",
    bad: "Wrong code.", locked: "Too many attempts: try again in 15 minutes.", auth: "Session expired, please sign in again.", generic: "Something went wrong.",
  },
} as const;

export function TwoFactor({ scope, enabled, lang = "it" }: { scope: Scope; enabled: boolean; lang?: "it" | "en" }) {
  const T = tx[lang], router = useRouter();
  const [setup, setSetup] = useState<{ qr: string; secret: string } | null>(null);
  const [codes, setCodes] = useState<string[] | null>(null);
  const [code, setCode] = useState(""), [err, setErr] = useState("");
  const [busy, start] = useTransition();
  const fail = (e?: string) => setErr(e === "bad" ? T.bad : e === "locked" ? T.locked : e === "auth" ? T.auth : T.generic);

  if (codes) {
    return (
      <div className="tfbox">
        <p>{T.saved}</p>
        <ul className="tfcodes">{codes.map((c) => <li key={c}><code>{c}</code></li>)}</ul>
        <div className="row">
          <button type="button" className="btn small ghost" onClick={() => navigator.clipboard?.writeText(codes.join("\n"))}><Copy size={14} /> {T.copy}</button>
          <button type="button" className="btn small" onClick={() => { setCodes(null); router.refresh(); }}>{T.done}</button>
        </div>
      </div>
    );
  }
  if (setup) {
    return (
      <form className="tfbox" onSubmit={(e) => { e.preventDefault(); setErr(""); start(async () => {
        const r = await confirmTwoFactor(scope, code).catch(() => null);
        if (!r) return fail(); if (!r.ok) return fail(r.error);
        setSetup(null); setCode(""); setCodes(r.codes);
      }); }}>
        <p>{T.step1}</p>
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img src={setup.qr} width={220} height={220} alt="QR" className="tfqr" />
        <p className="meta">{T.manual} <code>{setup.secret}</code></p>
        <p>{T.step2}</p>
        <input value={code} onChange={(e) => setCode(e.target.value)} inputMode="numeric" autoComplete="one-time-code" placeholder={T.code} maxLength={7} required aria-label={T.code} />
        {err && <p className="cerr" role="alert">{err}</p>}
        <div className="row">
          <button className="btn small" disabled={busy}>{T.confirm}</button>
          <button type="button" className="btn small ghost" onClick={() => { setSetup(null); setErr(""); }}>{T.cancel}</button>
        </div>
      </form>
    );
  }
  return (
    <div className="tfbox">
      <p className={`tfstate ${enabled ? "on" : ""}`}>{enabled ? <ShieldCheck size={18} /> : <ShieldOff size={18} />} {enabled ? T.on : T.off}</p>
      {enabled ? (
        <form onSubmit={(e) => { e.preventDefault(); setErr(""); start(async () => {
          const r = await disableTwoFactor(scope, code).catch(() => null);
          if (!r) return fail(); if (!r.ok) return fail(r.error);
          setCode(""); router.refresh();
        }); }}>
          <p className="meta">{T.disableLead}</p>
          <input value={code} onChange={(e) => setCode(e.target.value)} placeholder={T.code} required aria-label={T.code} />
          {err && <p className="cerr" role="alert">{err}</p>}
          <button className="btn small danger" disabled={busy}>{T.disable}</button>
        </form>
      ) : (
        <>
          <p className="meta">{T.lead}</p>
          {err && <p className="cerr" role="alert">{err}</p>}
          <button type="button" className="btn small" disabled={busy} onClick={() => start(async () => {
            setErr("");
            const r = await beginTwoFactor(scope).catch(() => null);
            if (!r) return fail(); if (!r.ok) return fail(r.error);
            setSetup({ qr: r.qr, secret: r.secret });
          })}>{T.enable}</button>
        </>
      )}
    </div>
  );
}
